# Cuts Zak's "Battle Worn" crest (tools/art/rkg_crests.png, his own RKG art) out of the sheet, makes its outline
# symmetric from the clean left edge, and writes engine/crest_art.js: the picture (JPEG, data URI) and the outline
# in shield units (width 1.1, top at y=0, y down negative) with matching texture coords.
import base64, io, json, os
import numpy as np
from PIL import Image
from scipy import ndimage
here=os.path.dirname(os.path.abspath(__file__))
im=Image.open(os.path.join(here,'art','rkg_crests.png')).convert('RGB')
c=im.crop((430,590,830,1150)); a=np.asarray(c).astype(float); L=a.mean(2)
lab,n=ndimage.label(L<75); edge=set(np.unique(np.concatenate([lab[0],lab[-1],lab[:,0],lab[:,-1]])))-{0}
sh=ndimage.binary_fill_holes(~np.isin(lab,list(edge))); sh=ndimage.binary_opening(sh,iterations=2)
lab2,n2=ndimage.label(sh); sh=lab2==1+int(np.argmax(ndimage.sum(sh,lab2,range(1,n2+1))))
ys,xs=np.where(sh); y0,y1=ys.min(),ys.max(); x0,x1=xs.min(),xs.max(); cx=(x0+x1)/2
left=[]
for y in range(y0,y1+1,6):
  r=np.where(sh[y,:int(cx)])[0]
  if len(r): left.append((float(r.min())+2.0,float(y)))
left.append((cx,float(y1)-1))
pts=left+[(2*cx-x,y) for x,y in reversed(left[:-1])]
# the texture: the bounding box, 2× up
bx0,by0,bx1,by1=int(x0),int(y0),int(round(2*cx-x0))+1,int(y1)+1
tex=c.crop((bx0,by0,bx1,by1)); S=2; tex=tex.resize((tex.width*S,tex.height*S),Image.LANCZOS)
buf=io.BytesIO(); tex.save(buf,'JPEG',quality=88); uri='data:image/jpeg;base64,'+base64.b64encode(buf.getvalue()).decode()
k=1.1/(bx1-bx0)
poly=[[round((x-cx)*k,4),round(-(y-y0)*k,4),round((x-bx0)/(bx1-bx0),4),round(1-(y-by0)/(by1-by0),4)] for x,y in pts]
out=os.path.join(here,'..','engine','crest_art.js')
open(out,'w').write('// generated by tools/crest_art.py from Zak\'s RKG crest sheet — do not edit\nconst CREST_ART='+json.dumps({'img':uri,'poly':poly,'w':tex.width,'h':tex.height,'H':round((by1-by0)*k,4)})+';\n')
print(len(poly),'pts', tex.size, len(uri)//1024,'KB')
